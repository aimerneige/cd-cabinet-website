import { test, expect } from '@playwright/test'
import { discardEditor } from './helpers/artwork'

test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('.shelf-cd')).toHaveCount(24)
})

test('multiple artist names survive reload, support search and can be removed separately', async ({ page }) => {
  await page.getByRole('button', { name: 'Add recording' }).click()
  await page.getByRole('textbox', { name: 'Album title', exact: true }).fill('Shared Session')
  await page.getByRole('textbox', { name: 'Artist', exact: true }).fill('  Simon & Garfunkel  ')
  await page.getByRole('button', { name: 'Add artist' }).click()
  await page.getByRole('textbox', { name: 'Artist 2', exact: true }).fill('   ')
  await page.getByRole('button', { name: 'Add recording', exact: true }).click()
  await expect(page.locator('.editor-error')).toHaveText('Enter an album title and artist.')
  await page.getByRole('textbox', { name: 'Artist 2', exact: true }).fill('  Guest Artist  ')
  await page.getByRole('button', { name: 'Add artist' }).click()
  await page.getByRole('textbox', { name: 'Artist 3', exact: true }).fill('Third Artist')
  await page.getByRole('button', { name: 'Remove artist 2', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Artist 2', exact: true })).toHaveValue('Third Artist')
  await page.getByRole('textbox', { name: 'Artist 2', exact: true }).fill('Guest Artist')
  const cover = (await page.getByRole('img', { name: 'Cover preview', exact: true }).getAttribute('src'))!
  expect(decodeURIComponent(cover)).toContain('Simon &amp; Garfunkel / Guest Artist')
  await page.getByRole('button', { name: 'Add recording', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await expect(page.locator('.shelf-cd')).toHaveCount(25)
  await page.reload()
  const search = page.getByRole('textbox', { name: 'Search albums and artists' })
  await search.fill('Guest Artist')
  await expect(page.locator('.shelf-cd')).toHaveCount(1)
  await page.getByRole('button', { name: 'Open Shared Session by Simon & Garfunkel / Guest Artist', exact: true }).click()
  await expect(page.locator('.album-heading > p')).toHaveText('Simon & Garfunkel / Guest Artist')
  await page.getByRole('button', { name: 'Edit recording', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Artist', exact: true })).toHaveValue('Simon & Garfunkel')
  await expect(page.getByRole('textbox', { name: 'Artist 2', exact: true })).toHaveValue('Guest Artist')
  await page.getByRole('button', { name: 'Remove artist 1', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Artist', exact: true })).toHaveValue('Guest Artist')
  await expect(page.getByRole('button', { name: /Remove artist/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Open Shared Session by Guest Artist', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search albums and artists' }).fill('Simon & Garfunkel')
  await expect(page.locator('.shelf-cd')).toHaveCount(0)
})

test('mainstream genres are available and custom genres persist, filter and can be reused on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Add recording' }).click()
  const genre = page.getByRole('combobox', { name: 'Genre', exact: true })
  for (const name of ['Pop', 'Rock', 'Hip-Hop', 'R&B', 'Electronic', 'Jazz', 'Classical', 'Folk', 'Country', 'Blues', 'Reggae', 'Metal', 'Latin', 'Soundtrack']) {
    await expect(genre.getByRole('option', { name, exact: true })).toHaveCount(1)
  }
  await page.getByRole('textbox', { name: 'Album title', exact: true }).fill('Dream Session')
  await page.getByRole('textbox', { name: 'Artist', exact: true }).fill('Dream Artist')
  await page.getByRole('button', { name: 'Add custom genre' }).click()
  await page.getByRole('textbox', { name: 'Custom genre', exact: true }).fill('   ')
  await page.getByRole('button', { name: 'Add recording', exact: true }).click()
  await expect(page.locator('.editor-error')).toHaveText('Enter a genre name.')
  await page.getByRole('textbox', { name: 'Custom genre', exact: true }).fill('  Shoegaze  ')
  const cover = (await page.getByRole('img', { name: 'Cover preview', exact: true }).getAttribute('src'))!
  expect(decodeURIComponent(cover)).toContain('Shoegaze')
  await page.screenshot({ path: 'test-results/custom-genre-mobile.png' })
  await page.getByRole('button', { name: 'Add recording', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Shoegaze', exact: true }).click()
  await expect(page.locator('.shelf-cd')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Open Dream Session by Dream Artist', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: 'Open Dream Session by Dream Artist', exact: true }).click()
  await expect(page.locator('.album-meta')).toContainText('Shoegaze')
  await page.getByRole('button', { name: 'Edit recording', exact: true }).click()
  await expect(genre).toHaveValue('Shoegaze')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Add recording' }).click()
  await genre.selectOption('Shoegaze')
  await expect(genre.getByRole('option', { name: 'Shoegaze', exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: 'Add custom genre' }).click()
  await page.getByRole('textbox', { name: 'Custom genre', exact: true }).fill('sHoEgAzE')
  await page.getByRole('textbox', { name: 'Album title', exact: true }).fill('Another Dream')
  await page.getByRole('textbox', { name: 'Artist', exact: true }).fill('Another Artist')
  await page.getByRole('button', { name: 'Add recording', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Shoegaze', exact: true }).click()
  await expect(page.locator('.shelf-cd')).toHaveCount(2)
  await expect(page.getByRole('button', { name: 'sHoEgAzE', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Add recording' }).click()
  await page.getByRole('button', { name: 'Add custom genre' }).click()
  await page.getByRole('textbox', { name: 'Custom genre', exact: true }).fill('Unsaved Genre')
  await discardEditor(page)
  await page.getByRole('button', { name: 'Add recording' }).click()
  await expect(genre.getByRole('option', { name: 'Unsaved Genre', exact: true })).toHaveCount(0)
})

test('legacy recordings remain editable and localized default names reuse existing genres', async ({ page }) => {
  await page.getByRole('button', { name: 'Open Blue Hours by The Paper Kites', exact: true }).click()
  await page.getByRole('button', { name: 'Edit recording', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Artist', exact: true })).toHaveValue('The Paper Kites')
  await expect(page.getByRole('textbox', { name: 'Artist 2', exact: true })).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: 'Genre', exact: true })).toHaveValue('Indie Folk')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await page.reload()
  await page.getByRole('combobox', { name: 'Select language', exact: true }).selectOption('zh')
  await page.getByRole('button', { name: '添加专辑' }).click()
  const genre = page.getByRole('combobox', { name: '流派', exact: true })
  await expect(genre.getByRole('option', { name: '流行', exact: true })).toHaveCount(1)
  await expect(genre.getByRole('option', { name: '古典', exact: true })).toHaveCount(1)
  await page.getByRole('textbox', { name: '专辑名称', exact: true }).fill('爵士合作')
  await page.getByRole('textbox', { name: '音乐人', exact: true }).fill('音乐人甲')
  await page.getByRole('button', { name: '添加音乐人' }).click()
  await page.getByRole('textbox', { name: '音乐人 2', exact: true }).fill('音乐人乙')
  await page.getByRole('button', { name: '添加自定义流派' }).click()
  await page.getByRole('textbox', { name: '自定义流派', exact: true }).fill(' 爵士 ')
  await page.getByRole('button', { name: '添加专辑', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: '爵士', exact: true }).click()
  await expect(page.locator('.shelf-cd')).toHaveCount(7)
  await page.getByRole('button', { name: '打开 音乐人甲 / 音乐人乙 的《爵士合作》', exact: true }).click()
  await page.getByRole('button', { name: '编辑唱片', exact: true }).click()
  await expect(genre).toHaveValue('Jazz')
})
