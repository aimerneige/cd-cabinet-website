import { test, expect, type Page } from '@playwright/test'
import { selectBookletPage } from './helpers/artwork'

async function draft(page: Page, title: string) {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Add recording' }).click()
  await page.getByRole('textbox', { name: 'Album title', exact: true }).fill(title)
  await page.getByRole('textbox', { name: 'Artist', exact: true }).fill('Page Artist')
}

test('booklet pagination edits one page at a time and preserves drafts through moves, deletion and saving', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await draft(page, 'Paged Booklet')
  await expect(page.getByRole('main', { name: 'Add a recording', exact: true })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  for (let number = 1; number <= 12; number += 1) {
    await page.getByRole('button', { name: 'Add text page', exact: true }).click()
    await expect(page.locator('.booklet-pages-editor li')).toHaveCount(1)
    await page.getByRole('textbox', { name: `Page ${number} title`, exact: true }).fill(`Chapter ${number}`)
    await page.getByRole('textbox', { name: `Page ${number} text / lyrics`, exact: true }).fill(`Lyrics ${number}`)
  }
  const navigation = page.getByRole('navigation', { name: 'Edit booklet pages', exact: true })
  await expect(navigation.getByRole('button', { name: 'Next page', exact: true })).toBeDisabled()
  await expect(navigation.locator('small')).toHaveText('12 / 12')
  await selectBookletPage(page, 3)
  await page.getByRole('textbox', { name: 'Page 3 text / lyrics', exact: true }).fill('Revised lyrics')
  await navigation.getByRole('button', { name: 'Previous page', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Page 2 text / lyrics', exact: true })).toHaveValue('Lyrics 2')
  await navigation.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Page 3 text / lyrics', exact: true })).toHaveValue('Revised lyrics')
  await page.getByRole('button', { name: 'Move page 3 up', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Page 2 title', exact: true })).toHaveValue('Chapter 3')
  await expect(page.getByRole('textbox', { name: 'Page 2 text / lyrics', exact: true })).toHaveValue('Revised lyrics')
  await selectBookletPage(page, 3)
  await page.getByRole('button', { name: 'Remove page 3', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Page 3 title', exact: true })).toHaveValue('Chapter 4')
  await expect(navigation.getByRole('combobox').locator('option')).toHaveCount(11)
  await expect(page.locator('.booklet-pages-editor li')).toHaveCount(1)
  await page.locator('.booklet-pages-editor').screenshot({ path: 'test-results/booklet-editor-pagination-mobile.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: 'Add recording', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await page.reload()
  const recording = page.getByRole('button', { name: 'Open Paged Booklet by Page Artist', exact: true })
  await recording.click()
  await page.getByRole('button', { name: 'Read booklet', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Booklet page thumbnails', exact: true }).getByRole('button')).toHaveCount(13)
  await page.getByRole('button', { name: 'Go to booklet page 3', exact: true }).click()
  await expect(page.locator('.reader-paper h3')).toHaveText('Chapter 3')
  await expect(page.locator('.reader-paper p')).toHaveText('Revised lyrics')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Edit recording', exact: true }).click()
  await selectBookletPage(page, 8)
  await navigation.getByRole('button', { name: 'Previous page', exact: true }).click()
  await expect(page.locator('.editor-footer > span')).toHaveText('Saved on this browser.')
  await page.getByRole('button', { name: 'Back to collection', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
  await expect(recording).toBeFocused()
})

test('Escape cannot dismiss the editor and leaving a changed page requires an explicit discard', async ({ page }) => {
  await draft(page, 'Keep my draft')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('textbox', { name: 'Album title', exact: true })).toHaveValue('Keep my draft')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Back to collection', exact: true }).click()
  const confirmation = page.getByRole('alertdialog', { name: 'Discard unsaved changes?', exact: true })
  await expect(confirmation.getByRole('button', { name: 'Keep editing', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(confirmation).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'Album title', exact: true })).toHaveValue('Keep my draft')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await confirmation.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(page.locator('.album-editor')).toBeVisible()
  await page.getByRole('button', { name: 'Back to collection', exact: true }).click()
  await confirmation.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await expect(page.locator('.shelf-cd')).toHaveCount(24)
  await expect(page.getByRole('button', { name: 'Open Keep my draft by Page Artist', exact: true })).toHaveCount(0)
})

test('refresh warns before losing a draft and saving removes the navigation warning', async ({ page }) => {
  await draft(page, 'Refresh Protected')
  const prompt = page.waitForEvent('dialog')
  const reload = page.evaluate(() => window.location.reload())
  const warning = await prompt
  expect(warning.type()).toBe('beforeunload')
  await warning.dismiss()
  await reload
  await expect(page.getByRole('textbox', { name: 'Album title', exact: true })).toHaveValue('Refresh Protected')
  await page.getByRole('button', { name: 'Add recording', exact: true }).click()
  await expect(page.locator('.album-editor')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Open Refresh Protected by Page Artist', exact: true })).toBeVisible()
})
